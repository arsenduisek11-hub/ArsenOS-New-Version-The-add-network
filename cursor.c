void draw_cursor(int x, int y, uint32_t* fb, int width) {
    for(int i = 0; i < 16; i++) {
        for(int j = 0; j < 16; j++) {
            if(cursor_sprite[i][j] == 1) {
                int px = x + j;
                int py = y + i;
                if(px >= 0 && px < 1024 && py >= 0 && py < 768) {
                    fb[py * width + px] = 0xFFFFFF;
                }
            } else if(cursor_sprite[i][j] == 2) {
                int px = x + j;
                int py = y + i;
                if(px >= 0 && px < 1024 && py >= 0 && py < 768) {
                    fb[py * width + px] = 0x000000;
                }
            }
        }
    }
}
